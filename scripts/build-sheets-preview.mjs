// Generates sheets.html, the local preview / QA page for the formula-sheets bundle. It reproduces
// the LIVE page's structure (section ids, a hero with the print button and jump nav, one list per
// block) from src/sheets/lines.js, so the browser test exercises the same DOM the bundle meets on
// ziptility.com/tools/formula-sheets. Run: node scripts/build-sheets-preview.mjs
import fs from 'node:fs';
import { SHEETS } from '../src/sheets/lines.js';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const sections = SHEETS.map((sh, i) => `
<section id="${sh.id}" class="${i % 2 ? 'section_fgp-n50' : 'section_fgp-white'}"><div class="padding-global"><div class="container-large"><div class="article-intro_wrap"><div class="state-richtext">
<h2>${esc(sh.title)}</h2>
<p>The reference, in plain operator notation, for the math on this exam.</p>
${sh.blocks.map((b) => `<h2>${esc(b.h)}</h2>\n<ul>\n${b.lines.map((l) => `<li>${esc(l.imp)}</li>`).join('\n')}\n</ul>`).join('\n')}
<h2>Use it</h2>
<p>Study from this sheet, then work the problems by hand.</p>
</div></div></div></div></section>`).join('\n');
const html = `<!DOCTYPE html>
<!-- GENERATED by scripts/build-sheets-preview.mjs from src/sheets/lines.js. Do not edit by hand.
     Local preview / QA page for the formula-sheets bundle: mirrors the live page's structure
     (section ids, hero print button, jump nav, one list per block) and the production embed
     (mount div + script). Run npm run build:sheets:dev and open this file directly. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex">
<title>Operator formula sheets: preview</title>
<style>body{font-family:system-ui,sans-serif;margin:0;color:#0c1f30} .padding-global{padding:0 24px} .container-large{max-width:900px;margin:0 auto} section{padding:24px 0} .section_fgp-n50{background:#f4f6f8} ul{padding-left:20px} li{margin:4px 0} .chip-list_row a{margin-right:10px}
@media print{.fs-print-wrap{display:none !important}}
@media print{ #fs-jump-nav{display:none !important} #water-treatment,#water-distribution,#wastewater-treatment,#wastewater-collection{page-break-before:always;break-before:page} }</style>
<script>document.addEventListener('DOMContentLoaded',function(){var b=document.querySelector('.fs-print-btn');if(b){b.addEventListener('click',function(e){e.preventDefault();window.print();});}});</script>
</head><body>
<section id="main" class="section_fgp-linen"><div class="padding-global"><div class="container-large"><div class="article-intro_wrap">
<h1 class="mkt-fgp_h1">Operator formula sheets</h1>
<p class="mkt-fgp_dek">The formulas for all four certification tracks, in plain operator notation, on one page.</p>
<p class="article-intro_p">Print this page. Each sheet starts on its own page.</p>
<div id="ziptility-sheets"></div>
<div class="fs-print-wrap"><a type="button" href="#" class="fs-print-btn w-button">Print these sheets</a></div>
<div id="fs-jump-nav" class="chip-list_row">${SHEETS.map((sh) => `<a href="#${sh.id}" class="chip-list_chip">${esc(sh.title.replace(' formula sheet', ''))}</a>`).join('')}</div>
</div></div></div></section>
${sections}
<script defer src="./dist/sheets-dev.js"></script>
</body></html>
`;
fs.writeFileSync(new URL('../sheets.html', import.meta.url), html);
console.log('sheets.html written:', SHEETS.length, 'sheets,', SHEETS.reduce((n, s) => n + s.blocks.reduce((m, b) => m + b.lines.length, 0), 0), 'lines');
